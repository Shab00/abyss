"""Strategy base class, order intents, and fill representations.

Strategies subclass `Strategy` and implement the callbacks they care about.
The engine calls these in response to market events, then collects any
`Order` intents returned from `generate_orders()` and applies them to the
simulated book.
"""
from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from enum import Enum
from typing import Optional

from abyss.strategy.context import StrategyContext


class OrderSide(Enum):
    BUY = 1
    SELL = -1


class OrderType(Enum):
    LIMIT = "limit"
    MARKET = "market"


@dataclass
class Order:
    """Order intent generated by a strategy.

    Orders are declarative — they say what the strategy wants. The engine
    decides whether/how to fill them based on the current book and the
    fill model.
    """
    side: OrderSide
    price: Optional[float]      # None for MARKET orders
    qty: float                  # positive BTC
    order_type: OrderType = OrderType.LIMIT
    tag: str = ""               # optional label for telemetry ("mm_bid_1")

    def __post_init__(self):
        if self.qty <= 0:
            raise ValueError(f"Order qty must be positive, got {self.qty}")
        if self.order_type == OrderType.LIMIT and self.price is None:
            raise ValueError("LIMIT order requires a price")
        if self.order_type == OrderType.MARKET and self.price is not None:
            raise ValueError("MARKET order must not set price")


@dataclass
class Fill:
    """A completed or partial fill of an Order."""
    recv_ts_ns: int
    side: OrderSide
    price: float
    qty: float
    tag: str = ""
    is_maker: bool = True       # True = passive fill, False = aggressive

    def notional(self) -> float:
        return self.price * self.qty

    def signed_qty(self) -> float:
        return self.side.value * self.qty


class Strategy(ABC):
    """Abstract base for all ABYSS strategies.

    Subclasses implement the callbacks they care about. Default
    implementations are no-ops so simple strategies don't need boilerplate.

    Lifecycle:
        on_start(ctx)          — called once at backtest start
        on_book_update(ctx)    — each depth snapshot (100 ms)
        on_trade(ctx, trade)   — each trade print
        on_timer(ctx)          — periodic tick (default every 1 s)
        generate_orders(ctx)   — called after each callback; returns
                                 a list of Order intents
        on_end(ctx)            — called once at backtest end
    """

    # Set by the engine before on_start; strategies shouldn't overwrite.
    name: str = "base"

    def __init__(self, **params):
        """Store strategy parameters. Subclasses can pre-declare defaults
        via a `default_params()` classmethod."""
        merged = {**self.default_params(), **params}
        for k, v in merged.items():
            setattr(self, k, v)

    @classmethod
    def default_params(cls) -> dict:
        """Return default parameter values. Override in subclasses."""
        return {}

    # --- Lifecycle hooks (override as needed) ---

    def on_start(self, ctx: StrategyContext) -> None:
        """Called once before the first event."""

    def on_book_update(self, ctx: StrategyContext) -> None:
        """Called on each depth snapshot."""

    def on_trade(self, ctx: StrategyContext, trade: dict) -> None:
        """Called on each trade print. `trade` has keys price, qty, is_buyer_maker."""

    def on_timer(self, ctx: StrategyContext) -> None:
        """Called on timer events (default: every 1 second)."""

    def on_end(self, ctx: StrategyContext) -> None:
        """Called once after the last event."""

    # --- Order generation ---

    def generate_orders(self, ctx: StrategyContext) -> list[Order]:
        """Return new order intents based on current state.

        Called by the engine after each callback. Default: no orders.
        Strategies that manage persistent working orders should check the
        engine's working-order state (passed via context in future versions)
        to avoid duplicate submissions.
        """
        return []

    # --- Introspection ---

    def describe(self) -> dict:
        """Return a dict of parameters for logging / comparison reports."""
        return {
            "name": self.name,
            "params": {
                k: v for k, v in vars(self).items()
                if not k.startswith("_") and k != "name"
            },
        }
